import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await page.goto('https://musicdistrict.netlify.app/', { waitUntil: 'domcontentloaded' })
  await page.locator('#map-button').click()
  await page.locator('#map-places [data-map-target="palmEntrance"]').click()
  await page.waitForTimeout(6000)
  assert.equal(await page.locator('#context-name').textContent(), 'PALM ROOM')
  await page.locator('#interact').click()
  await page.locator('#action-primary').click()
  await page.waitForTimeout(800)
  await page.locator('#view-setup').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'STAGE PREVIEW', { timeout: 15000 })
  await page.locator('#interact').click()
  await page.locator('[data-stage-setup="light"]').click()
  await page.locator('[data-stage-setup="monitors"]').click()
  await page.locator('[data-stage-setup="backdrop"]').click()
  await page.locator('[data-stage-save]').click()
  await page.locator('#show-draft-form [name="title"]').fill('Friday Open Mic')
  await page.locator('#show-draft-form [name="start"]').fill('2026-10-23T19:00')
  await page.locator('#show-draft-form button[type="submit"]').click()
  assert.match(await page.locator('#stage-setup-progress').innerText(), /3\/3/)
  assert.match(await page.locator('#show-draft-status').innerText(), /Friday Open Mic/)
  assert.equal(await page.evaluate(() => localStorage.getItem('scene-show-draft')?.includes('Friday Open Mic')), true)
  await page.screenshot({ path: '../docs/evidence/netlify-palm-room-stage-plan-mobile.png', fullPage: true })
  await page.locator('#action-close').click()
  await page.screenshot({ path: '../docs/evidence/netlify-palm-room-stage-placed-mobile.png', fullPage: true })
  console.log('Live Palm Room stage setup and show draft passed in Chrome')
} finally { await browser.close() }
