import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('https://musicdistrict.netlify.app/', { waitUntil: 'domcontentloaded', timeout: 45000 })
  await page.locator('#map-button').click()
  await page.locator('#map-places [data-map-target="studio"]').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'CITY STUDIO', null, { timeout: 25000 })
  await page.locator('#interact').click()
  await page.locator('#action-primary').click()
  await page.waitForFunction(() => document.querySelector('#place-name')?.textContent?.includes('City Studio'), null, { timeout: 15000 })
  await page.locator('#nav-create').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'BEAT DESK', null, { timeout: 45000 })
  await page.locator('#interact').click()
  await page.locator('#beat-render').click()
  await page.waitForTimeout(2000)
  assert.match(await page.locator('#beat-status').innerText(), /master saved/)
  await page.locator('#beat-close').click()
  await page.locator('#map-button').click()
  await page.locator('#map-places [data-map-target="palmEntrance"]').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'MUSIC SQUARE', null, { timeout: 25000 })
  await page.locator('#interact').click()
  await page.locator('#action-primary').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'PALM ROOM', null, { timeout: 25000 })
  await page.locator('#interact').click()
  await page.locator('#action-primary').click()
  await page.locator('#view-setup').click()
  await page.waitForFunction(() => document.querySelector('#context-name')?.textContent === 'PREVIEW ON STAGE', null, { timeout: 45000 })
  await page.locator('#interact').click()
  assert.match(await page.locator('#action-primary').innerText(), /Rehearse light cues/)
  await page.locator('#action-primary').click()
  await page.locator('#stage-cue-hud').waitFor({ state: 'visible' })
  assert.equal(await page.locator('#action-sheet').isVisible(), false)
  await page.waitForFunction(() => document.querySelector('#stage-cue-time')?.textContent !== '0:00 / 0:30', null, { timeout: 5000 })
  await page.locator('[data-cue-look="sunset"]').click()
  await page.waitForTimeout(600)
  await page.locator('[data-cue-look="spotlight"]').click()
  await page.screenshot({ path: '../docs/evidence/netlify-palm-room-cue-rehearsal-mobile.png', fullPage: true })
  await page.locator('#stage-cue-stop').click()
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('scene-stage-cues') || '[]').length), 2)
  await page.locator('#interact').click()
  assert.match(await page.locator('#action-primary').innerText(), /Replay saved show/)
  await page.locator('#action-primary').click()
  await page.locator('#stage-cue-hud').waitFor({ state: 'visible' })
  assert.equal(await page.locator('[data-cue-look="sunset"]').isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('Live music creation, rehearsal cue recording, and replay passed in Chrome')
} finally { await browser.close() }
